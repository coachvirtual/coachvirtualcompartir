// Keep Lucide's renderer and license; ship only icon definitions used by this app.
const fs = require('node:fs');
const path = require('node:path');
const { icons } = require('lucide');
const root = path.resolve(__dirname, '..');
const files = fs.readdirSync(root).filter(name => name.endsWith('.html'))
  .concat(fs.readdirSync(path.join(root, 'js')).filter(name => name.endsWith('.js')).map(name => 'js/' + name));
const selected = {};
for (const file of files) {
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  // Includes literals inside dynamic attributes and icon names in section data.
  for (const [, name] of source.matchAll(/["'`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)["'`]/g)) {
    const key = name.replace(/(^|-)([a-z0-9])/g, (_, separator, letter) => letter.toUpperCase());
    if (icons[key]) selected[key] = icons[key];
  }
}
const lucideRoot = path.dirname(require.resolve('lucide/package.json'));
const upstream = fs.readFileSync(path.join(lucideRoot, 'dist/umd/lucide.js'), 'utf8');
const renderer = upstream.slice(upstream.indexOf('  const createElement ='), upstream.indexOf('  const defaultAttributes ='));
let createIcons = upstream.slice(upstream.indexOf('  const createIcons ='), upstream.indexOf('  exports.AArrowDown ='));
if (!renderer || !createIcons.includes('document.querySelectorAll(`[${nameAttr}]`)')) {
  throw new Error('Lucide renderer changed; review the scoped renderer before building.');
}
// Scope to a container and leave existing SVGs intact. Default calls still work.
createIcons = createIcons.replace('attrs = {} } = {})', 'attrs = {}, root = document } = {})')
  .replace('document.querySelectorAll(`[${nameAttr}]`)', 'root.querySelectorAll(`[${nameAttr}]:not(svg)`)')
  .replace('document.querySelectorAll("[icon-name]")', 'root.querySelectorAll("[icon-name]:not(svg)")');
const license = fs.readFileSync(path.join(lucideRoot, 'LICENSE'), 'utf8');
const definitions = Object.fromEntries(Object.entries(selected).sort(([a], [b]) => a.localeCompare(b)));
const output = `/* Generated by npm run build:icons. Lucide 0.468.0\n${license}\n*/\n(function () {\n'use strict';\n${renderer}\nconst iconAndAliases = ${JSON.stringify(definitions)};\n${createIcons}\nwindow.lucide = { icons: iconAndAliases, createElement: createElement$1, createIcons };\n})();\n`;
fs.writeFileSync(path.join(root, 'js/vendor/lucide-icons.js'), output);
console.log(`Lucide: ${Object.keys(definitions).length} icons, ${Buffer.byteLength(output)} bytes`);
